class DiaryYear:
    """One CE Diary year, kept in a form that makes replicate re-weighting cheap.

    entries(col) returns weighted purchase entries per CU-week by UCC, where col 0 is the
    final weight FINLWT21 and cols 1..44 are the BRR replicate weights WTREP01..WTREP44.
    """

    def __init__(self, yy):
        d = RAW / "ce" / f"diary{yy}"
        if not d.exists():
            url = (CE_CSV if int(yy) >= 22 else CE_CSV_OLD).format(yy=yy)
            z, _ = fetch(url, RAW / "ce" / f"diary{yy}.zip")
            zipfile.ZipFile(z).extractall(RAW / "ce")
        self.year = 2000 + int(yy)
        exp = pd.concat([pd.read_csv(f, dtype={"NEWID": str, "UCC": str}, usecols=["NEWID", "UCC", "COST", "ALLOC"])
                         for f in sorted(d.glob("expd*.csv"))])
        head = pd.read_csv(sorted(d.glob("fmld*.csv"))[0], nrows=0)
        rep = [f"WTREP{i:02d}" for i in range(1, NREP + 1)]
        self.have_rep = [c for c in rep if c in head.columns]
        self.missing_rep = [c for c in rep if c not in head.columns]
        fml = pd.concat([pd.read_csv(f, dtype={"NEWID": str}, usecols=["NEWID", "FINLWT21"] + self.have_rep)
                         for f in sorted(d.glob("fmld*.csv"))])
        fml = fml.drop_duplicates("NEWID").reset_index(drop=True)

        # WTREP is blank for CUs not assigned to that half-sample -> weight 0 (BLS PUMD guide, sec. 6.3)
        self.Wm = np.zeros((len(fml), NREP + 1))
        self.Wm[:, 0] = pd.to_numeric(fml.FINLWT21, errors="coerce").fillna(0.0).values
        self.na_rep = 0
        for i, c in enumerate(rep, start=1):
            if c in self.have_rep:
                v = pd.to_numeric(fml[c], errors="coerce")
                self.na_rep += int(v.isna().sum())
                self.Wm[:, i] = v.fillna(0.0).values
            else:
                self.Wm[:, i] = self.Wm[:, 0]      # no replicate -> contributes no variance
        self.W = self.Wm[:, 0].sum()
        self.colsum = self.Wm.sum(axis=0)

        row_of = pd.Series(np.arange(len(fml)), index=fml.NEWID.values)
        exp = exp.assign(row=exp.NEWID.map(row_of)).dropna(subset=["row"])
        exp["row"] = exp.row.astype(int)
        pairs = exp.groupby(["UCC", "row"], sort=True).size().reset_index(name="n")
        self.ucc, self.uidx = np.unique(pairs.UCC.values, return_inverse=True)
        self.rows = pairs.row.values
        self.cnt = pairs.n.values.astype(float)

        idx = pd.Index(self.ucc, name="ucc")
        w = self.Wm[self.rows, 0]
        self.freq = pd.DataFrame({
            "entries_per_cuweek": self.entries(0).values,
            "spend_per_cuweek": ((exp.COST * self.Wm[exp.row.values, 0]).groupby(exp.UCC).sum() / self.W).reindex(idx).fillna(0.0).values,
            "share_buying": np.bincount(self.uidx, weights=w, minlength=len(self.ucc)) / self.W,
        }, index=idx).reset_index()
        self.freq["diary_year"] = self.year
        log.info("diary %s: %d CU-weeks (sum FINLWT21 %.3g), %d expd rows, %d UCCs, %d replicate cols (%d blank cells -> 0)",
                 yy, len(fml), self.W, len(exp), len(self.ucc), len(self.have_rep), self.na_rep)
        if self.missing_rep:
            log.warning("diary %s: MISSING replicate columns %s - those replicates reuse FINLWT21 (no variance contribution)",
                        yy, self.missing_rep)

    def entries(self, col):
        w = self.Wm[:, col]
        tot = self.colsum[col]
        if tot <= 0:
            return pd.Series(0.0, index=self.ucc)
        v = self.cnt * w[self.rows]
        return pd.Series(np.bincount(self.uidx, weights=v, minlength=len(self.ucc)) / tot, index=self.ucc)


def concordance():
    p, _ = fetch(CONC, RAW / "ce" / "ce-cpi-concordance.xlsx")
    df = pd.read_excel(p, header=None, dtype=str)
    hdr = df.index[df[0].str.strip().str.upper().eq("UCC")][0]
    df = df.iloc[hdr + 1:, :5]
    df.columns = ["ucc", "eli", "ucc_title", "eli_title", "source"]
    df = df.dropna(subset=["ucc", "eli"])
    df = df[df.ucc.str.match(r"^\d{6}$")]
    df["ucc"] = df.ucc.str.strip(); df["eli"] = df.eli.str.strip().str.upper()
    return df


def map_eli_to_leaf(eli, leaf_set, item_codes=None):
    """ELI 'FA011' -> stratum 'SEFA01' -> published leaf; walk up if not published."""
    for k in (4, 3, 2):
        c = "SE" + eli[:k]
        if c in leaf_set:
            return c
    return None


# ---------------------------------------------------------------------------
# UCC -> leaf item linear operators
# ---------------------------------------------------------------------------
def ucc_item_matrix(conc, leaf, split="exp"):
    """A[i,j] = share of UCC j's purchase entries assigned to leaf item i.

    29 UCCs fan out to several ELIs.  split='exp' apportions them by the target items'
    expenditure weight (proxy for BLS's unpublished special adjustment factors);
    split='equal' gives each mapped target an equal share.  A UCC whose targets all have
    zero/absent expenditure weight falls back to an equal split either way.
    """
    leaf_set = set(leaf.index)
    m = conc[["ucc", "eli"]].copy()
    m["item_code"] = m.eli.map(lambda e: map_eli_to_leaf(e, leaf_set))
    if split == "exp":
        m["wt"] = m.item_code.map(leaf).fillna(0.0)
    else:
        m["wt"] = m.item_code.notna().astype(float)
    m["wt"] = m.wt.where(m.groupby("ucc").wt.transform("sum") > 0, 1.0)
    m["share"] = m.wt / m.groupby("ucc").wt.transform("sum")
    uccs = np.array(sorted(m.ucc.unique()))
    ui = {u: j for j, u in enumerate(uccs)}
    items = list(leaf.index)
    ii = {c: i for i, c in enumerate(items)}
    A = np.zeros((len(items), len(uccs)))
    for r in m.dropna(subset=["item_code"]).itertuples():
        A[ii[r.item_code], ui[r.ucc]] += r.share
    return uccs, A


def class_operator(leaf):
    """C: aggregate leaf frequency to the expenditure class (item_code[:4], e.g. SEFA) and
    spread it back over that class's leaves in proportion to expenditure weight."""
    items = list(leaf.index)
    key = np.array([c[:4] for c in items])
    same = (key[:, None] == key[None, :]).astype(float)
    tot = same @ leaf.values
    sh = np.where(tot > 0, leaf.values / np.where(tot > 0, tot, 1.0), 1.0 / same.sum(axis=1))
    return same * sh[:, None]


# ---------------------------------------------------------------------------
# December-chained Laspeyres
# ---------------------------------------------------------------------------
MIN_COV = 0.90     # a month is only priced if >= this share of the scheme's leaf weight has data


class Chainer:
    """Vectorised December-chained Laspeyres; arithmetic identical to dec_chained().

    A month is skipped unless leaves carrying at least MIN_COV of the scheme's total weight
    have both a December base index and a current index.  Without this, October 2025 (no CPI
    release - government shutdown) was priced off the ~11 leaf items that happen to carry an
    Oct-2025 observation, which produced a spurious index level and YoY.
    """

    def __init__(self, im, leaves_by_year, pub_sa0):
        self.pub = pub_sa0
        self.skipped = {}
        self.years = sorted(leaves_by_year)
        piv = im.pivot_table(index="item_code", columns="ym", values="idx_nsa")
        self.items, self.months, self.R, self.M = {}, {}, {}, {}
        for y in self.years:
            items = list(leaves_by_year[y])
            self.items[y] = items
            bym = f"{y}-12"
            b = piv[bym].reindex(items).values if bym in piv.columns else np.full(len(items), np.nan)
            ms, rows = [], []
            for mo in range(1, 13):
                ym = f"{y+1}-{mo:02d}"
                if ym not in piv.columns:
                    continue
                ms.append(ym)
                rows.append(piv[ym].reindex(items).values / b)
            R = np.array(rows) if rows else np.zeros((0, len(items)))
            self.months[y] = ms
            self.M[y] = np.isfinite(R).astype(float)
            self.R[y] = np.where(np.isfinite(R), R, 0.0)

    def run(self, weights_by_year, note=None):
        out, skipped = {}, []
        for y in self.years:
            if y not in weights_by_year or not self.months[y]:
                continue
            w = pd.Series(weights_by_year[y]).reindex(self.items[y]).fillna(0.0).values.astype(float)
            tot = w.sum()
            if tot <= 0:
                continue
            den = self.M[y] @ w
            num = self.R[y] @ w
            for k, ym in enumerate(self.months[y]):
                if den[k] >= MIN_COV * tot:
                    out[ym] = num[k] / den[k]
                elif den[k] > 0:
                    skipped.append((ym, den[k] / tot))
        for ym, c in skipped:
            self.skipped[ym] = max(self.skipped.get(ym, 0.0), c)
        if note and skipped:
            log.info("%s: dropped %d month(s) with leaf coverage < %.0f%%: %s", note, len(skipped), MIN_COV * 100,
                     [(ym, f"{100*c:.1f}%") for ym, c in skipped])
        s = pd.Series(out).sort_index()
        level, last_dec = {}, None
        for ym, rel in s.items():
            y = int(ym[:4]) - 1
            if last_dec is None or last_dec[0] != y:
                last_dec = (y, level.get(f"{y}-12", self.pub.get(f"{y}-12")))
            level[ym] = last_dec[1] * rel
        lv = pd.Series(level).sort_index()
        p = pd.PeriodIndex(lv.index, freq="M")
        prev = pd.Series(lv.values, index=(p + 12).astype(str))
        yoy = (lv / prev.reindex(lv.index) - 1) * 100
        return lv, yoy


def dec_chained(im, weights_by_year, pub_sa0):
    """Dec-chained Laspeyres over leaves. weights_by_year: {weight_year: Series(item_code -> weight)}.
    Kept as a module-level entry point (it is the comparison standard).
    Months with less than MIN_COV of the leaf weight priced are dropped, not extrapolated."""
    return Chainer(im, {y: list(w.index) for y, w in weights_by_year.items()}, pub_sa0).run(weights_by_year)


