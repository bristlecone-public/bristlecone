#!/usr/bin/env python3
"""P1 - frequency-weighted CPI.

Reweights CPI leaf items by *purchase frequency* (CE Diary Survey: weighted purchase
entries per consumer-unit-week) instead of expenditure share, then builds a
December-chained Laspeyres index exactly like the P0 replica so the two are comparable.

  p1_salience.py [--years=22,23,24] [--no-boot] [--no-extend] [--force-extend]

  --years         diary years to load (2-digit).            default 22,23,24
  --no-boot       skip the 44-replicate BRR bootstrap.
  --no-extend     do not try to back-fill Dec-2017..2019 CPI relative-importance weights.
  --force-extend  re-parse and re-load the archived 2017-2019 weights even if present.

Naming: the *user-facing* label for this method is "frequency-weighted". The historical
table and column names ('salience', p1_item_salience.w_sal, scheme 'salience', 'blend50')
are kept unchanged because other pipelines read them.

Schemes written to p1_index
  official_replica  December relative importance (= P0 replica of the published CPI-U NSA)
  salience          purchase-entry frequency weights                 [label: frequency-weighted]
  blend50           0.5 * official_replica + 0.5 * salience
  bill_salience     frequency weights with a monthly-bill floor      [label: bill-adjusted frequency]
  bill_blend50      0.5 * official_replica + 0.5 * bill_salience

Tables
  p1_ucc_freq(diary_year, ucc, entries_per_cuweek, spend_per_cuweek, share_buying)
  p1_item_salience(diary_year, item_code, freq, w_sal, w_exp)
  p1_index(scheme, ym, idx, yoy)
  p1_sensitivity(variant, ym, yoy)          -- robustness variants of the frequency index
  p1_boot(scheme, ym, yoy, se)              -- se = BRR standard error of (scheme YoY - official replica YoY)

out/p1_salience.json schema
  generated_at        ISO-8601 UTC
  latest_month        'YYYY-MM' of the last month with a YoY for every scheme
  diary_years         [int]     CE Diary years used for frequency
  weight_years        [int]     December relative-importance years used for chaining
  labels              {scheme: user-facing label}
  method              {bill_frequency_per_cuweek, bill_items:[{item_code,item_name}], multi_eli_split, ...}
  bootstrap           {replicates, formula, source, missing:{diary_year: n}}
  series              [{ym, published_yoy, official_replica_yoy,
                        salience_yoy, salience_se, blend50_yoy,
                        bill_salience_yoy, bill_salience_se, bill_blend50_yoy}]
                      *_se are BRR standard errors of the gap vs official_replica, in pp.
  sensitivity         [{variant, ym, yoy}]  full monthly series for each robustness variant
  sensitivity_latest  [{variant, yoy, gap}] latest_month only, gap = yoy - official replica yoy
  sensitivity_range   {ym, min_gap, max_gap, range_pp}
  items_latest        [{item_code, name, w_exp, w_sal, w_bill, yoy, contrib_exp, contrib_sal, gap_driver}]
  notes               [str]
"""
