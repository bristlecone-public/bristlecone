def main(years, do_boot=True, do_extend=True, force_extend=False):
    con = init_db(); con.executescript(SCHEMA1); con.commit()
    if do_extend:
        extend_weights(con, force=force_extend)

    im = pd.read_sql("SELECT item_code, ym, idx_nsa FROM cpi_item_month", con)
    names = pd.read_sql("SELECT item_code, item_name FROM cu_item", con).set_index("item_code").item_name
    wexp = pd.read_sql("SELECT weight_year, item_code, weight_u FROM cpi_weight WHERE is_leaf=1 AND matched=1", con)
    pub = im[im.item_code == "SA0"].set_index("ym").idx_nsa
    conc = concordance()
    log.info("concordance: %d rows, %d UCCs (%d flagged Diary-source), %d UCCs fan out to >1 ELI",
             len(conc), conc.ucc.nunique(), conc[conc.source.str.upper().str.startswith("D")].ucc.nunique(),
             int((conc.groupby("ucc").eli.nunique() > 1).sum()))

    # ---- diary micro data -------------------------------------------------
    dys = {}
    for yy in years:
        o = DiaryYear(yy)
        dys[o.year] = o
        con.execute("DELETE FROM p1_ucc_freq WHERE diary_year=?", (o.year,))
        con.executemany("INSERT INTO p1_ucc_freq VALUES(?,?,?,?,?)",
                        o.freq[["diary_year", "ucc", "entries_per_cuweek", "spend_per_cuweek", "share_buying"]].values.tolist())
    con.commit()
    avail = sorted(dys)
    base_ent = {dy: dys[dy].entries(0) for dy in avail}
    totW = sum(dys[dy].W for dy in avail)
    pooled_ent = (pd.concat([base_ent[dy] * dys[dy].W for dy in avail], axis=1).fillna(0.0).sum(axis=1) / totW)

    def pick(wy):
        le = [a for a in avail if a <= wy]
        return wy if wy in avail else (max(le) if le else avail[0])

    # ---- per weight-year operators ---------------------------------------
    wyears = sorted(int(y) for y in wexp.weight_year.unique())
    leaf_by = {wy: wexp[wexp.weight_year == wy].set_index("item_code").weight_u for wy in wyears}
    maps = {(wy, sp): ucc_item_matrix(conc, leaf_by[wy], sp) for wy in wyears for sp in ("exp", "equal")}
    cops = {wy: class_operator(leaf_by[wy]) for wy in wyears}
    billmask = {wy: np.array([c in BILL_ITEMS for c in leaf_by[wy].index]) for wy in wyears}
    ch = Chainer(im, {wy: list(leaf_by[wy].index) for wy in wyears}, pub)
    log.info("weight years %s (leaves %s)", wyears, [len(leaf_by[w]) for w in wyears])

    # coverage diagnostics on the newest weight year
    top = max(wyears)
    fy = base_ent[pick(top)]
    known = set(conc.ucc)
    nomap = fy[~fy.index.isin(known)]
    log.info("diary UCCs with no concordance row: %d (%.1f%% of entries): %s",
             len(nomap), 100 * nomap.sum() / fy.sum(), nomap.sort_values(ascending=False).head(12).index.tolist())
    _, A_top = maps[(top, "exp")]
    e_top = fy.reindex(maps[(top, "exp")][0]).fillna(0.0).values
    log.info("weight year %d: %.1f%% of concordance-mapped entry mass lands on a published leaf", top,
             100 * (A_top @ e_top).sum() / max(e_top.sum(), 1e-12))

    def weights_for(ent_fn, split="exp", agg="item", bills=False):
        out = {}
        for wy in wyears:
            uccs, A = maps[(wy, split)]
            f = A @ ent_fn(wy).reindex(uccs).fillna(0.0).values
            if agg == "class":
                f = cops[wy] @ f
            if bills:
                f = np.where(billmask[wy], np.maximum(f, BILL_FREQ), f)
            s = f.sum()
            out[wy] = pd.Series(f / s * 100 if s > 0 else f, index=leaf_by[wy].index)
        return out

    base_fn = lambda wy: base_ent[pick(wy)]
    w_off = {wy: leaf_by[wy] / leaf_by[wy].sum() * 100 for wy in wyears}
    w_frq = weights_for(base_fn)
    w_bil = weights_for(base_fn, bills=True)
    blend = lambda a: {wy: 0.5 * w_off[wy] + 0.5 * a[wy] for wy in wyears}

    schemes = {"official_replica": w_off, "salience": w_frq, "blend50": blend(w_frq),
               "bill_salience": w_bil, "bill_blend50": blend(w_bil)}
    res = {}
    for name, wb in schemes.items():
        lv, yoy = ch.run(wb, note=f"scheme {name}")
        res[name] = (lv, yoy)
        con.execute("DELETE FROM p1_index WHERE scheme=?", (name,))
        con.executemany("INSERT INTO p1_index VALUES(?,?,?,?)",
                        [(name, ym, float(lv[ym]), None if pd.isna(yoy[ym]) else float(yoy[ym])) for ym in lv.index])
    con.commit()

    item_rows = []
    for wy in wyears:
        dy = pick(wy)
        uccs, A = maps[(wy, "exp")]
        f = A @ base_ent[dy].reindex(uccs).fillna(0.0).values
        for i, c in enumerate(leaf_by[wy].index):
            item_rows.append((dy, c, float(f[i]), float(w_frq[wy][c]), float(w_off[wy][c])))
        log.info("weight year %d (diary %d): %d leaves, %d with frequency>0, top frequency weights: %s",
                 wy, dy, len(leaf_by[wy]), int((w_frq[wy] > 0).sum()),
                 [(names.get(c, c)[:28], round(v, 2)) for c, v in w_frq[wy].sort_values(ascending=False).head(6).items()])
    con.execute("DELETE FROM p1_item_salience")
    con.executemany("INSERT OR REPLACE INTO p1_item_salience VALUES(?,?,?,?,?)", item_rows)
    con.commit()

    # ---- sensitivity trio -------------------------------------------------
    variants = {
        "split_exp":    weights_for(base_fn, split="exp"),      # = headline
        "split_equal":  weights_for(base_fn, split="equal"),
        "agg_item":     w_frq,                                  # = headline
        "agg_class":    weights_for(base_fn, agg="class"),
        "diary_pooled": weights_for(lambda wy: pooled_ent),
    }
    for dy in avail:
        variants[f"diary_{dy}"] = weights_for(lambda wy, d=dy: base_ent[d])
    sens = {}
    con.execute("DELETE FROM p1_sensitivity")
    for v, wb in variants.items():
        _, yoy = ch.run(wb, note=f"variant {v}")
        sens[v] = yoy
        con.executemany("INSERT INTO p1_sensitivity VALUES(?,?,?)",
                        [(v, ym, None if pd.isna(yoy[ym]) else float(yoy[ym])) for ym in yoy.index])
    con.commit()

    yoy_off = res["official_replica"][1]
    months = [ym for ym in res["salience"][1].index if not pd.isna(res["salience"][1][ym]) and not pd.isna(yoy_off.get(ym, np.nan))]
    latest = months[-1]
    gaps = {v: float(sens[v][latest] - yoy_off[latest]) for v in variants}
    lo, hi = min(gaps.values()), max(gaps.values())
    log.info("SENSITIVITY %s: gap (variant YoY - official replica YoY) across %d variants: min %+.3f max %+.3f, RANGE %.3f pp",
             latest, len(gaps), lo, hi, hi - lo)
    for v in sorted(gaps, key=gaps.get):
        log.info("   %-14s yoy %.3f  gap %+.3f", v, sens[v][latest], gaps[v])

    # ---- BRR bootstrap ----------------------------------------------------
    # BLS CE PUMD, "Getting Started Guide" sec. 6.3 (bls.gov/cex/pumd-getting-started-guide.htm):
    #     sigma = sqrt( sum_{WTREP=1..44} (X_WTREP - X)^2 / 44 )
    # i.e. variance = (1/44) * sum (theta_r - theta)^2.  The PUMD replicate weights are already
    # doubled half-sample weights (median WTREP/FINLWT21 = 2.00, sum WTREP_r = sum FINLWT21), so
    # no Fay factor is applied.  Under the Fay k=0.5 convention (variance = (4/44)*sum) every SE
    # below would be exactly 2x larger.
    boot = {}
    if do_boot:
        bschemes = {"salience": dict(bills=False), "bill_salience": dict(bills=True)}
        acc = {s: [] for s in bschemes}
        blend_acc = {"blend50": [], "bill_blend50": []}
        for r in range(1, NREP + 1):
            ent_r = {dy: dys[dy].entries(r) for dy in avail}
            fn = lambda wy: ent_r[pick(wy)]
            for s, kw in bschemes.items():
                wb = weights_for(fn, **kw)
                acc[s].append(ch.run(wb)[1])
                blend_acc["blend50" if s == "salience" else "bill_blend50"].append(ch.run(blend(wb))[1])
            if r % 11 == 0:
                log.info("bootstrap replicate %d/%d", r, NREP)
        for s, full in (("salience", res["salience"][1]), ("bill_salience", res["bill_salience"][1]),
                        ("blend50", res["blend50"][1]), ("bill_blend50", res["bill_blend50"][1])):
            reps = acc[s] if s in acc else blend_acc[s]
            gap0 = full - yoy_off
            D = pd.concat([(y - yoy_off) - gap0 for y in reps], axis=1)
            se = np.sqrt((D ** 2).sum(axis=1) / NREP).where(gap0.notna())
            boot[s] = se
            con.execute("DELETE FROM p1_boot WHERE scheme=?", (s,))
            con.executemany("INSERT INTO p1_boot VALUES(?,?,?,?)",
                            [(s, ym, None if pd.isna(full.get(ym, np.nan)) else float(full[ym]),
                              None if pd.isna(se.get(ym, np.nan)) else float(se[ym])) for ym in full.index])
        con.commit()
        log.info("bootstrap: %s", ", ".join(f"{s} {latest} gap {float(res[s][1][latest]-yoy_off[latest]):+.3f} +/- {float(boot[s][latest]):.3f} pp"
                                            for s in ("salience", "bill_salience")))

    # ---- validation of the replica against published ----------------------
    p = pd.PeriodIndex(pub.index, freq="M")
    pub_yoy = (pub / pd.Series(pub.values, index=(p + 12).astype(str)).reindex(pub.index) - 1) * 100
    d = (res["official_replica"][1] - pub_yoy.reindex(res["official_replica"][1].index)).dropna()
    log.info("official_replica vs published YoY: n=%d %s..%s, mean %+.3f, max|diff| %.3f pp",
             len(d), d.index[0], d.index[-1], d.mean(), d.abs().max())
    for yr in sorted({ym[:4] for ym in d.index}):
        dd = d[[i for i in d.index if i.startswith(yr)]]
        log.info("   %s: mean %+.3f max|diff| %.3f", yr, dd.mean(), dd.abs().max())

    # ---- JSON -------------------------------------------------------------
    latest_wy = int(latest[:4]) - 1
    prev_ym = f"{latest_wy}-{latest[5:]}"
    tbl = pd.DataFrame({
        "w_exp": w_off[latest_wy], "w_sal": w_frq[latest_wy], "w_bill": w_bil[latest_wy],
        "yoy": im[im.ym == latest].set_index("item_code").idx_nsa / im[im.ym == prev_ym].set_index("item_code").idx_nsa * 100 - 100,
    }).dropna()
    tbl["name"] = tbl.index.map(lambda c: names.get(c, c))
    tbl["contrib_exp"] = tbl.w_exp * tbl.yoy / 100
    tbl["contrib_sal"] = tbl.w_sal * tbl.yoy / 100
    tbl["gap_driver"] = tbl.contrib_sal - tbl.contrib_exp

    def g(s, ym):
        v = s.get(ym, np.nan)
        return None if pd.isna(v) else round(float(v), 3)

    out = {
        "generated_at": pd.Timestamp.now("UTC").isoformat(),
        "latest_month": latest,
        "diary_years": avail,
        "weight_years": wyears,
        "labels": {"official_replica": "Official (expenditure-weighted) replica",
                   "salience": "Frequency-weighted CPI",
                   "blend50": "50/50 expenditure + frequency",
                   "bill_salience": "Bill-adjusted frequency-weighted CPI",
                   "bill_blend50": "50/50 expenditure + bill-adjusted frequency"},
        "method": {
            "frequency": "share of weighted CE Diary purchase entries per consumer-unit-week, mapped UCC -> ELI -> published item stratum",
            "multi_eli_split": "expenditure-weight split of the 29 multi-ELI UCCs (see sensitivity variant split_equal)",
            "aggregation_level": "published item (see sensitivity variant agg_class)",
            "bill_frequency_per_cuweek": round(BILL_FREQ, 6),
            "bill_rule": "max(diary frequency, 1/4.345 entries per CU-week) for the listed items only",
            "bill_items": [{"item_code": c, "item_name": names.get(c, n)} for c, n in sorted(BILL_ITEMS.items())],
            "index": "December-chained Laspeyres over the same leaf universe as the P0 replica",
            "min_leaf_coverage": MIN_COV,
            "excluded_months": {ym: round(100 * c, 1) for ym, c in sorted(ch.skipped.items())},
        },
        "bootstrap": {
            "replicates": NREP,
            "formula": "sigma = sqrt( sum_{r=1..44} (theta_r - theta)^2 / 44 )",
            "source": "BLS CE PUMD Getting Started Guide sec. 6.3 'Estimating sampling error' (https://www.bls.gov/cex/pumd-getting-started-guide.htm)",
            "quantity": "standard error of (scheme YoY - official replica YoY), percentage points",
            "note": "PUMD replicate weights are doubled half-sample weights, so no Fay factor is applied; under the Fay k=0.5 convention (variance = 4/44 * sum) every SE would be exactly 2x larger.",
            "blank_replicate_cells": {str(dy): int(dys[dy].na_rep) for dy in avail},
            "missing_replicate_columns": {str(dy): dys[dy].missing_rep for dy in avail},
        },
        "series": [{"ym": ym,
                    "published_yoy": g(pub_yoy, ym),
                    "official_replica_yoy": g(yoy_off, ym),
                    "salience_yoy": g(res["salience"][1], ym),
                    "salience_se": g(boot["salience"], ym) if "salience" in boot else None,
                    "blend50_yoy": g(res["blend50"][1], ym),
                    "blend50_se": g(boot["blend50"], ym) if "blend50" in boot else None,
                    "bill_salience_yoy": g(res["bill_salience"][1], ym),
                    "bill_salience_se": g(boot["bill_salience"], ym) if "bill_salience" in boot else None,
                    "bill_blend50_yoy": g(res["bill_blend50"][1], ym),
                    "bill_blend50_se": g(boot["bill_blend50"], ym) if "bill_blend50" in boot else None}
                   for ym in months],
        "sensitivity": [{"variant": v, "ym": ym, "yoy": g(sens[v], ym)} for v in sorted(sens) for ym in months],
        "sensitivity_latest": [{"variant": v, "yoy": round(float(sens[v][latest]), 3), "gap": round(gaps[v], 3)}
                               for v in sorted(gaps, key=gaps.get)],
        "sensitivity_range": {"ym": latest, "min_gap": round(lo, 3), "max_gap": round(hi, 3), "range_pp": round(hi - lo, 3)},
        "items_latest": tbl.sort_values("w_sal", ascending=False).round(3).reset_index().rename(columns={"index": "item_code"}).to_dict(orient="records"),
        "notes": [
            "'Frequency-weighted' means each published CPI item is weighted by how often households record buying it in the CE Diary, not by how much they spend. Table and column names keep the older word 'salience' for compatibility.",
            "The Diary is a two-week purchase log, so recurring bills collected by the CE Interview survey (rent, owners' equivalent rent, insurance, tuition, most medical care) score near zero frequency by construction. The bill_salience variant puts a one-entry-per-month floor under a documented list of such items; it is an assumption, not a measurement.",
            "Purchase-entry counts also reflect how finely BLS splits an item into UCCs: an item recorded as several UCCs accumulates more entries than an equally common item recorded as one. The agg_class sensitivity variant aggregates frequency at the expenditure-class level to show how much that matters.",
            "All indexes are December-chained Laspeyres over the same leaf universe; official_replica tracks the published all-items NSA YoY closely (see log for the year-by-year diff).",
            f"A month is only priced when leaves carrying at least {MIN_COV:.0%} of the scheme's weight have data, so October 2025 (no CPI release) is absent from every scheme rather than being priced off the handful of items that happen to have an observation.",
            "Descriptive only - no causal claim that any of these indexes measures inflation as experienced or perceived.",
        ],
    }
    (OUT / "p1_salience.json").write_text(json.dumps(out, indent=1, allow_nan=False))

    def line(ym):
        s = f"{ym}: published {g(pub_yoy,ym)} | replica {g(yoy_off,ym)} | frequency {g(res['salience'][1],ym)}"
        if "salience" in boot:
            s += f" (SE {g(boot['salience'],ym)})"
        s += f" | blend50 {g(res['blend50'][1],ym)} | bill {g(res['bill_salience'][1],ym)}"
        if "bill_salience" in boot:
            s += f" (SE {g(boot['bill_salience'],ym)})"
        return s + f" | bill_blend50 {g(res['bill_blend50'][1],ym)}"

    for ym in (latest, "2022-06", "2024-06", "2019-06", "2020-06"):
        if ym in months:
            log.info("=== %s", line(ym))
    log.info("biggest gap drivers (frequency minus expenditure contribution, pp): %s",
             [(r.name[:30], round(r.gap_driver, 2)) for r in tbl.sort_values("gap_driver", key=abs, ascending=False).head(8).itertuples()])


if __name__ == "__main__":
    if "--help" in sys.argv or "-h" in sys.argv:
        print(__doc__); sys.exit(0)
    years, boot, ext, fext = ["22", "23", "24"], True, True, False
    for a in sys.argv[1:]:
        if a.startswith("--years"):
            years = a.split("=")[1].split(",")
        elif a == "--no-boot":
            boot = False
        elif a == "--no-extend":
            ext = False
        elif a == "--force-extend":
            fext = True
    main(years, do_boot=boot, do_extend=ext, force_extend=fext)
