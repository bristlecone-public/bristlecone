def _nkey(s):
    s = re.sub(r"\(\d+\)", "", s).lower()
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9 ]", " ", s)).strip()


def ri_txt_to_html(txt):
    """Fixed-width RI table (BLS ri-archive *.txt) -> the minimal HTML p0_fetch.load_weights parses.

    Item names use dot leaders and may wrap over 2-3 lines (the wrapped tail is indented
    further than the head of the entry); values are 'nn.nnn' or '.nnn' (CPI-U then CPI-W).
    """
    rows, pend = [], []
    for raw in txt.replace("\r", "").split("\n"):
        line = raw.rstrip()
        if not line.strip():
            pend = []
            continue
        ind = len(line) - len(line.lstrip())
        if "special aggregate" in line.lower():
            rows.append("<tr><td>Special aggregate indexes</td></tr>")
            pend = []
            continue
        nums = list(NUM_RE.finditer(line))
        if len(nums) >= 2:
            name = line[:nums[-2].start()].rstrip(" .").strip()
            if pend and ind > pend[0][0]:                 # deeper than the head of the entry
                name = " ".join(t for _, t in pend) + " " + name
            pend = []
            if not name:
                continue
            name = RI_RENAME.get(_nkey(name), name)
            rows.append(f"<tr><th>{name}</th><td>{nums[-2].group(1)}</td><td>{nums[-1].group(1)}</td></tr>")
        else:
            pend = (pend + [(ind, line.strip())])[-3:]
    return GEN_MARK + "\n<table>\n" + "\n".join(rows) + "\n</table>\n"


def extend_weights(con, years=EXTEND_YEARS, force=False):
    """Stage archived December relative-importance tables as HTML, then hand them to
    p0_fetch.load_weights *unmodified* so the name->code matching, level and leaf logic is
    byte-identical to the 2020+ weights.  Returns the list of years actually loaded."""
    have = {r[0] for r in con.execute("SELECT DISTINCT weight_year FROM cpi_weight").fetchall()}
    todo = [y for y in years if force or y not in have]
    if not todo:
        log.info("weight back-fill: %s already present", years)
        return []
    try:
        import p0_fetch
    except Exception as e:
        log.warning("weight back-fill skipped: cannot import p0_fetch (%s)", e)
        return []
    try:
        z, _ = fetch(RI_ARCHIVE, RAW / "weights" / "ri-archive-2010-2019.zip")
        zf = zipfile.ZipFile(z)
        names = {n.rsplit("/", 1)[-1]: n for n in zf.namelist()}
        staged = []
        for y in todo:
            src = names.get(f"{y}.txt")
            if not src:
                log.warning("weight back-fill: %d.txt not in %s", y, RI_ARCHIVE)
                continue
            dest = RAW / "weights" / f"{y}.htm"
            if dest.exists() and GEN_MARK not in dest.read_text(encoding="utf-8", errors="ignore"):
                log.warning("weight back-fill: %s exists and was not generated by us - leaving it alone", dest)
            else:
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(ri_txt_to_html(zf.read(src).decode("latin-1")), encoding="utf-8")
            staged.append(y)
        if not staged:
            return []
        orig = p0_fetch.fetch

        def local_first(url, d, **kw):          # serve the staged file; the live URL 404s
            return (d, True) if d.exists() else orig(url, d, **kw)
        p0_fetch.fetch = local_first
        try:
            p0_fetch.load_weights(con, years=staged)
        finally:
            p0_fetch.fetch = orig
        got = [y for y in staged if con.execute("SELECT 1 FROM cpi_weight WHERE weight_year=? LIMIT 1", (y,)).fetchone()]
        log.info("weight back-fill: loaded %s from the BLS RI text archive", got)
        return got
    except Exception as e:
        log.warning("weight back-fill FAILED (%s) - continuing with 2020+ weights only", e)
        return []


